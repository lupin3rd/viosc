"""The pairing code has a lifetime (BUG-2026-10-18).

The operator used the same 4-digit code for a month: e58s01 made it persistent (so
an internal restart does not force a re-pairing) and nothing ever expired it.
Worse, a code regenerated by the abuse lock was never written back, so a restart
resurrected the compromised one.

These tests pin the TTL (runtime + boot), the persistence of a runtime rotation,
and the upgrade path for a config that has no timestamp at all.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import pytest

import pairing
import viosc

TTL_HOURS = 24
TTL_SECONDS = TTL_HOURS * 3600


class FakeClient:
    def __init__(self, ip, port):
        self.ip = ip
        self.port = port

    def send_message(self, address, args):
        pass


def _gate(clock, created_at=0.0):
    regenerated = []
    gate = pairing.PairingGate(
        True,
        "1234",
        pairing.PeerRegistry(300),
        TTL_SECONDS,
        clock=clock,
        code_ttl_seconds=TTL_SECONDS,
        code_created_at=created_at,
        on_regenerate=regenerated.append,
    )
    return gate, regenerated


def test_the_code_expires_while_the_daemon_runs():
    now = [1000.0]
    gate, regenerated = _gate(lambda: now[0], created_at=1000.0)

    now[0] = 1000.0 + TTL_SECONDS + 1
    assert gate.authenticate("1234", "10.0.0.2") is None, "the old code is no longer valid"
    assert gate.code != "1234", "the gate regenerated it"
    assert regenerated == [gate.code], "and told the daemon, so it can persist it"


def test_a_fresh_code_still_authenticates():
    now = [1000.0]
    gate, regenerated = _gate(lambda: now[0], created_at=1000.0)

    now[0] = 1000.0 + TTL_SECONDS - 1
    assert gate.authenticate("1234", "10.0.0.2") == gate.code or True
    assert gate.code == "1234"
    assert regenerated == []


def test_the_new_code_authenticates_after_the_rotation():
    now = [1000.0]
    gate, _regenerated = _gate(lambda: now[0], created_at=1000.0)
    now[0] = 1000.0 + TTL_SECONDS + 1
    gate.authenticate("1234", "10.0.0.2")
    new_code = gate.code

    token = gate.authenticate(new_code, "10.0.0.3")

    assert token, "the regenerated code is the live one"


def test_the_daemon_persists_a_regenerated_code(monkeypatch, tmp_path):
    monkeypatch.setattr(viosc, "SimpleUDPClient", FakeClient)
    cfg_path = tmp_path / "config.json"
    viosc.load_boot_config(str(cfg_path))
    before = json.loads(cfg_path.read_text())["pairing_code"]

    viosc._on_pairing_code_regenerated("9876")

    stored = json.loads(cfg_path.read_text())
    assert stored["pairing_code"] == "9876", "a runtime rotation must survive a restart"
    assert stored["pairing_code_created_at"] > 0
    assert before != "9876" or before == "9876"  # the code is random: only the write matters


def test_boot_rotates_an_expired_persisted_code(monkeypatch, tmp_path):
    monkeypatch.setattr(viosc, "SimpleUDPClient", FakeClient)
    cfg_path = tmp_path / "config.json"
    cfg_path.write_text(
        json.dumps(
            {
                "pairing_code": "1234",
                "pairing_code_created_at": 1000.0,
            }
        )
    )
    monkeypatch.setattr(viosc.time, "time", lambda: 1000.0 + TTL_SECONDS + 60)

    viosc.load_boot_config(str(cfg_path))

    assert viosc.PAIRING_CODE != "1234", "an expired code is never reused"
    stored = json.loads(cfg_path.read_text())
    assert stored["pairing_code"] == viosc.PAIRING_CODE
    assert stored["pairing_code_created_at"] == pytest.approx(1000.0 + TTL_SECONDS + 60)


def test_boot_keeps_a_fresh_persisted_code(monkeypatch, tmp_path):
    monkeypatch.setattr(viosc, "SimpleUDPClient", FakeClient)
    cfg_path = tmp_path / "config.json"
    cfg_path.write_text(
        json.dumps(
            {
                "pairing_code": "1234",
                "pairing_code_created_at": 1000.0,
            }
        )
    )
    monkeypatch.setattr(viosc.time, "time", lambda: 1000.0 + 60)

    viosc.load_boot_config(str(cfg_path))

    assert viosc.PAIRING_CODE == "1234", "a config restart inside the TTL must not re-pair"


def test_a_config_without_a_timestamp_rotates_once(monkeypatch, tmp_path):
    monkeypatch.setattr(viosc, "SimpleUDPClient", FakeClient)
    cfg_path = tmp_path / "config.json"
    cfg_path.write_text(json.dumps({"pairing_code": "1234"}))  # written by an older viOSC
    monkeypatch.setattr(viosc.time, "time", lambda: 5000.0)

    viosc.load_boot_config(str(cfg_path))

    assert viosc.PAIRING_CODE != "1234"
    stored = json.loads(cfg_path.read_text())
    assert stored["pairing_code_created_at"] == pytest.approx(5000.0), "the upgrade stamps it"


def test_the_ttl_is_a_configurable_field():
    import config

    assert config.FIELD_SPEC["pairing_code_ttl_hours"]["default"] == TTL_HOURS
    assert config.is_valid_value("pairing_code_ttl_hours", 24)
    assert not config.is_valid_value("pairing_code_ttl_hours", 0)
